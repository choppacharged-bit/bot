# Список известных магазинов — держим отдельно, чтобы LLM не путал названия
# и не придумывал несуществующие магазины. Обновите этот список, если
# появятся новые точки.
KNOWN_STORES = [
    "Пионерский",
    "Утриш",
    "Джемете",
    "Озеро",
]

# ВАЖНО: человеческие названия магазинов (KNOWN_STORES) НЕ совпадают со
# значениями колонки 'Продажи'[Магазин] в реальной модели Power BI —
# там хранятся внутренние коды точек. Это соответствие подтверждено
# владельцем вручную и должно использоваться при генерации DAX-фильтров:
# в фильтр всегда подставляется код из этой таблицы, а не человеческое имя.
#
# Внимание: в обычных продажах/расходах/остатках Озеро и Джемете — РАЗНЫЕ
# точки с разными кодами. Объединение "Озеро+Джемете" действует ТОЛЬКО
# для таблицы 'Выручки' при расчёте зарплаты (см. описание таблицы 'Выручки'),
# и нигде больше.
STORE_CODE_MAP = {
    "Пионерский": "ОП_5_Анапа",
    "Утриш": "ОП_8_Утриш",
    "Озеро": "Гебея озеро",
    "Джемете": "ОП_1 Анапа Ленинградская",
}


def build_schema_prompt() -> str:
    """Собирает текстовое описание схемы для системного промпта LLM."""
    lines = []
    lines.append("СХЕМА ДАННЫХ POWER BI\n")
    lines.append(f"Известные магазины (используйте только эти названия): {', '.join(KNOWN_STORES)}\n")
    lines.append("СООТВЕТСТВИЕ ЧЕЛОВЕЧЕСКИХ НАЗВАНИЙ РЕАЛЬНЫМ КОДАМ В 'Продажи'[Магазин]:")
    lines.append(
        "(колонка 'Продажи'[Магазин] хранит НЕ человеческое название, а внутренний код точки — "
        "всегда подставляйте в DAX-фильтр код из списка ниже, а не название из вопроса пользователя)"
    )
    for friendly_name, code in STORE_CODE_MAP.items():
        lines.append(f"  - {friendly_name} -> 'Продажи'[Магазин] = \"{code}\"")
    lines.append(
        "  ВАЖНО: это соответствие для обычных продаж/расходов/остатков — здесь Озеро и "
        "Джемете РАЗНЫЕ точки с разными кодами. Объединение 'Озеро+Джемете' действует ТОЛЬКО "
        "для таблицы 'Выручки' при расчёте зарплаты, и нигде больше."
    )
    for table, info in SCHEMA.items():
        lines.append(f"\nТаблица '{table}' — {info['description']}")
        for col, dtype in info["columns"]:
            lines.append(f"  - '{table}'[{col}] — {dtype}")
        for m_name, m_desc in info.get("measures", []):
            lines.append(f"  - МЕРА '[{m_name}]' — {m_desc}")
    return "\n".join(lines)
