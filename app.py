def clean_token(raw_token: str) -> str:
    """Извлекает чистый токен Telegram вида 123456:ABC..."""
    if not raw_token:
        return ""
    match = re.search(r"(\d+:[A-Za-z0-9_-]+)", raw_token)
    return match.group(1) if match else raw_token.strip(" '\"[]")

